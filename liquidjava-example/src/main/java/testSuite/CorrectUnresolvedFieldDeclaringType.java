package testSuite;

import org.example.missing.Config;

// Fields whose declaring class cannot be resolved (#390)
@SuppressWarnings("unused")
public class CorrectUnresolvedFieldDeclaringType {
    private static final int MIN_ADMIN_PASSWORD_LENGTH = 8;

    static boolean shortPassword(Config config) {
        return config.httpAdminPassword.length() < MIN_ADMIN_PASSWORD_LENGTH;
    }

    void undeclaredField(Exception e) {
        log.error("get host name error:{}", e.getMessage()); // e.g., a field generated by Lombok
    }
}
